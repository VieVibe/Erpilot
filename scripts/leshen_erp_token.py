"""Log into the Le Shen ERP and refresh the Sa-Token used by the example adapter.

The Le Shen API authenticates with a raw Sa-Token in the Authorization header.
Tokens expire (and expire early after inactivity), so this helper re-logins and
rewrites examples/le-shen-erp/.env.local, keeping the workbench demo reproducible.

Usage:
    python scripts/leshen_erp_token.py
    python scripts/leshen_erp_token.py --username admin --password admin123
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import urllib.error
import urllib.request
from pathlib import Path

PROJECT = Path(__file__).resolve().parents[1]
ENV_FILE = PROJECT / "examples" / "le-shen-erp" / ".env.local"
DEFAULT_URL = "http://127.0.0.1:8082"


def login(base_url: str, username: str, password: str, timeout: float = 15.0) -> str:
    body = json.dumps({"username": username, "password": password}).encode("utf-8")
    request = urllib.request.Request(
        f"{base_url.rstrip('/')}/api/auth/login",
        data=body,
        headers={"Content-Type": "application/json; charset=utf-8", "Accept": "application/json"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            payload = json.loads(response.read().decode("utf-8"))
    except urllib.error.HTTPError as exc:
        raise SystemExit(f"login failed: HTTP {exc.code}") from exc
    except urllib.error.URLError as exc:
        raise SystemExit(f"cannot reach {base_url}: {exc.reason}") from exc
    data = payload.get("data") or {}
    token = data.get("token")
    if payload.get("code") != 200 or not token:
        raise SystemExit(f"login rejected: {payload.get('message')!r}")
    print(f"logged in as {data.get('username')} (userId={data.get('userId')}, "
          f"tenant={data.get('tenantName')})")
    return token


def probe(base_url: str, token: str, timeout: float = 15.0) -> None:
    """Verify the four read-only endpoints the adapter exposes."""
    endpoints = {
        "categories": "api/erp/category/page",
        "products": "api/erp/product/page",
        "warehouses": "api/erp/warehouse/page",
        "stock": "api/erp/stock/page",
    }
    for label, path in endpoints.items():
        request = urllib.request.Request(
            f"{base_url.rstrip('/')}/{path}?page=1&pageSize=1",
            headers={"Authorization": token, "Accept": "application/json"},
        )
        with urllib.request.urlopen(request, timeout=timeout) as response:
            payload = json.loads(response.read().decode("utf-8"))
        code = payload.get("code")
        if code == 200:
            total = (payload.get("data") or {}).get("total")
            print(f"  {label:<11} ok   total={total}")
        else:
            raise SystemExit(f"  {label:<11} rejected: code={code}")


def write_env(url: str, token: str, host_user: str, password: str) -> None:
    ENV_FILE.parent.mkdir(parents=True, exist_ok=True)
    ENV_FILE.write_text(
        "# Generated by scripts/leshen_erp_token.py - do not commit (gitignored)\n"
        f"LESHEN_ERP_URL={url}\n"
        f"LESHEN_ERP_SERVICE_TOKEN={token}\n"
        f"LESHEN_ERP_HOST_USER={host_user}\n"
        f"LESHEN_DEMO_PASSWORD={password}\n",
        encoding="utf-8",
    )
    print(f"wrote {ENV_FILE.relative_to(PROJECT)}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--url", default=os.getenv("LESHEN_ERP_URL", DEFAULT_URL))
    parser.add_argument("--username", default=os.getenv("LESHEN_ERP_LOGIN_USER", "admin"))
    parser.add_argument("--password", default=os.getenv("LESHEN_ERP_LOGIN_PASSWORD", "admin123"))
    parser.add_argument("--host-user", default=os.getenv("LESHEN_ERP_HOST_USER", "leshen-operator"))
    parser.add_argument(
        "--demo-password", default=os.getenv("LESHEN_DEMO_PASSWORD", "leshen-demo-2026")
    )
    parser.add_argument("--no-probe", action="store_true", help="skip endpoint verification")
    args = parser.parse_args()

    token = login(args.url, args.username, args.password)
    if not args.no_probe:
        probe(args.url, token)
    write_env(args.url, token, args.host_user, args.demo_password)
    return 0


if __name__ == "__main__":
    sys.exit(main())
